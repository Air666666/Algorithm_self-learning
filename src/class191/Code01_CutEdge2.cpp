// 给定一张无向图，一共n个点、m条边
// 图中可能存在多个连通区，对每个连通区求割边
// 先打印割边的总数量，然后从小到大打印所有割边的序号
// 请保证原图即使有重边和自环，答案依然正确
// 1 <= n <= 5 * 10^5
// 1 <= m <= 2 * 10^6
// 测试链接 : https://www.luogu.com.cn/problem/U582665
